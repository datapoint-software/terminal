#!/usr/bin/env python3
"""Generates the emulator's character width table from the Unicode Character Database.

Usage: python3 tools/unicode/generate_width_table.py <folder with the UCD files>

The folder must hold EastAsianWidth.txt, DerivedGeneralCategory.txt (from extracted/)
and emoji-data.txt (from emoji/), from https://www.unicode.org/Public/UCD/latest/ucd/.
The Unicode data is under the Unicode License v3.
"""

import pathlib
import re
import sys

MAX = 0x110000
LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")


def ranges(path):
    for raw in path.read_text(encoding="utf-8").splitlines():
        match = LINE.match(raw)
        if match:
            start = int(match.group(1), 16)
            end = int(match.group(2) or match.group(1), 16)
            yield start, end, match.group(3)


def version(path):
    first = path.read_text(encoding="utf-8").splitlines()[0]
    return re.search(r"-(\d+\.\d+\.\d+)\.txt", first).group(1)


def main(folder):
    folder = pathlib.Path(folder)
    width = [1] * MAX
    for start, end, value in ranges(folder / "EastAsianWidth.txt"):
        if value in ("W", "F"):
            for code in range(start, end + 1):
                width[code] = 2
    for start, end, value in ranges(folder / "emoji-data.txt"):
        if value == "Emoji_Presentation":
            for code in range(start, end + 1):
                width[code] = 2
    for start, end, value in ranges(folder / "DerivedGeneralCategory.txt"):
        if value in ("Mn", "Me", "Cf"):
            for code in range(start, end + 1):
                width[code] = 0
    for code in range(0x1160, 0x1200):
        width[code] = 0
    for code in range(0xD7B0, 0xD800):
        width[code] = 0
    width[0x00AD] = 1

    runs = []
    start = None
    for code in range(MAX + 1):
        value = width[code] if code < MAX else 1
        if start is not None and (value != runs_value or code == MAX):
            runs.append((start, code - 1, runs_value))
            start = None
        if start is None and value != 1 and code < MAX:
            start, runs_value = code, value

    out = pathlib.Path(__file__).resolve().parents[2] / "src/Datapoint.Terminal.Emulator/Unicode/WidthTable.g.cs"
    lines = [
        "// <auto-generated>",
        f"// Generated by tools/unicode/generate_width_table.py from Unicode {version(folder / 'EastAsianWidth.txt')}.",
        "// </auto-generated>",
        "",
        "namespace Datapoint.Terminal.Emulator.Unicode;",
        "",
        "internal static class WidthTable",
        "{",
        "    public static ReadOnlySpan<int> Starts =>",
        "    [",
    ]
    lines += [f"        0x{s:X},".rstrip() for s, _, _ in runs]
    lines += ["    ];", "", "    public static ReadOnlySpan<int> Ends =>", "    ["]
    lines += [f"        0x{e:X}," for _, e, _ in runs]
    lines += ["    ];", "", "    public static ReadOnlySpan<byte> Widths =>", "    ["]
    lines += [f"        {w}," for _, _, w in runs]
    lines += ["    ];", "}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(runs)} ranges written to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
